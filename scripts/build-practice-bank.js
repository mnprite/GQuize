/* Builds src/practice-bank.js (ORIGINAL-source-derived sentence bank for the practice games).
   Reads src/word-bank.js (itself generated from content/*.txt). Run: node scripts/build-practice-bank.js */
const fs=require('fs'),path=require('path');
const root=path.join(__dirname,'..');
global.window={};require(path.join(root,'src/word-bank.js'));
const cats=window.WORD_BANK.categories;

const COMMON_PREP=['in','on','at','from','to','for','with','by','of','about','under','over','since','into','after','before','between','through','off','up','down','near','behind','against','among','during','without','within','until','till','across','along','around','beside','besides','below','above'];
const COMMON_CONJ=['and','or','but','because','so','if','when','while','although','though','also','as','since','unless','until','before','after','than','that','whether'];

const clean=p=>p.replace(/^Q\.\s*\d+\.\s*/,'').replace(/\s*Note:.*$/,'').trim();
function split(raw){
  const t=raw.replace(/\([^)]*[A-Za-z][^)]*\)/g,' ');
  const m=[...t.matchAll(/[\u0900-\u097F]/g)];
  const idx=m.length?m[m.length-1].index+1:0;
  const hi=t.slice(0,idx).replace(/\s+/g,' ').trim();
  const tail=t.slice(idx).replace(/^[\s)।|\-–—.,:;?!]+/,'').replace(/\s+/g,' ').trim();
  const en=tail.split(/\s+\/\s+|(?<=[.?!”"])\s+(?=[A-Z“"])/).map(s=>s.trim()).filter(Boolean);
  return {hi,en};
}
const good=s=>/^[A-Z“"'][^\u0900-\u097F]*[.?!”"']$/.test(s)&&s.split(' ').length>=3;
const out={};
for(const cat of ['Prepositions','Conjunctions']){
  out[cat]=cats[cat].words.map(w=>{
    const nUses=w.uses.length;
    const common=(cat==='Prepositions'?COMMON_PREP:COMMON_CONJ);
    const single=w.variants.length===1&&!/\s/.test(w.variants[0]);
    const level=single&&common.includes(w.variants[0].toLowerCase())&&nUses<=3?1:(nUses>=4||w.variants.length>2?3:2);
    return {id:w.id,label:w.label,variants:w.variants,level,uses:w.uses.map(u=>{
      const seen=new Set(),sentences=[];
      for(const e of u.examples||[]){const s=split(e);for(const en of s.en){if(good(en)&&!seen.has(en)){seen.add(en);sentences.push({en,hi:s.hi});}}}
      return {id:u.id,hint:clean(u.prompt),answers:u.answers,sentences,source:u.source};
    })};
  });
}
const js='/* AUTO-GENERATED by scripts/build-practice-bank.js — ORIGINAL content only (from content/*.txt). Do not edit by hand. */\nwindow.PRACTICE_BANK = '+JSON.stringify(out,null,1)+';\n';
fs.writeFileSync(path.join(root,'src/practice-bank.js'),js);
for(const k in out){const n=out[k].reduce((t,w)=>t+w.uses.reduce((a,u)=>a+u.sentences.length,0),0);console.log(k,out[k].length,'words',n,'sentences');}
